// Generates the Nile PoC keyset and writes it to .env.nile (gitignored).
// Refuses to overwrite an existing file so funded keys are never clobbered.
import { writeFileSync, existsSync } from "node:fs";
import tw from "tronweb";

const { TronWeb } = tw;
const OUT = new URL("../../.env.nile", import.meta.url);

if (existsSync(OUT) && !process.argv.includes("--force")) {
  console.error(".env.nile already exists. Re-run with --force to regenerate (this discards funded keys).");
  process.exit(1);
}

const ROLES = [
  ["DEPLOYER", "deploys the token and both vaults; seeds vault USDT; funds the other roles", true],
  ["ENERGY_SPONSOR", "deploys both gateways (their origin); stakes TRX for Energy", false],
  ["MUUN", "vault owner; calls lock and relays the happy-path claimBySig", false],
  ["RECOVERY_CLAIMANT", "aggregate address P; must hold 0 TRX throughout", false],
  ["ZERO_TRX_RELAY", "activated third party with 0 TRX; broadcasts the tier-A recovery", false],
  ["RECIPIENT_WARM", "destination with a pre-existing USDT balance", false],
  ["RECIPIENT_COLD", "fresh destination, uninitialised USDT balance slot", false],
];

const lines = [
  "# Nile PoC keyset. Generated by scripts/tron/gen-accounts.mjs. Never commit.",
  "TRON_NETWORK=nile",
  "TRON_FULL_HOST=https://nile.trongrid.io",
  "TRONGRID_API_KEY=",
  "USDT_ADDRESS=TXYZopYRdj2D9XRtbG411XZZ3kM5VkAeBf",
  "AMOUNT_USDT=10",
  "RESERVATION_TTL_SECONDS=3600",
  "",
];

const table = [];
for (const [role, note, needsFaucet] of ROLES) {
  const a = TronWeb.createRandom();
  const priv = a.privateKey.replace(/^0x/, "");
  const base58 = TronWeb.address.fromPrivateKey(priv);
  const hex = TronWeb.address.toHex(base58);
  lines.push(`# ${role}: ${note}`);
  lines.push(`${role}_ADDRESS=${base58}`);
  lines.push(`${role}_PRIVATE_KEY=${priv}`);
  lines.push("");
  table.push({ role, base58, evm: "0x" + hex.slice(2), faucet: needsFaucet ? "YES" : "-" });
}

writeFileSync(OUT, lines.join("\n"), { mode: 0o600 });
console.table(table);
console.log("\nWrote .env.nile (mode 600, gitignored). Fund DEPLOYER at https://nileex.io/join/getJoinPage, then npm run fund:tron.");
